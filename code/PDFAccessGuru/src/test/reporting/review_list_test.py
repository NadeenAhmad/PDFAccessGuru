import base64
import io

import fitz
from PIL import Image

from pdfaccessguru.reporting.customer_report import (
    build_customer_report_images,
    build_customer_report_markdown,
    build_customer_report_pdf,
)
from pdfaccessguru.reporting.review_list import build_review_groups, estimated_minutes


def _png() -> str:
    buffer = io.BytesIO()
    Image.new("RGB", (40, 20), (200, 30, 30)).save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def _report() -> dict:
    figure_line = {
        "level": "review",
        "message": "Figure alternative text was generated by a language model: 'Bar chart of energy use'. Please check it.",
        "context": "Caption: Figure 3: Energy use 2015-2023",
        "image_png_base64": _png(),
    }
    logo_line = {"level": "review", "message": "Figure alternative text was generated by a language model: 'University logo'. Please check it."}
    return {
        "pdf_path": "in.pdf",
        "output_path": "out.pdf",
        "started_at": "2026-11-06T00:00:00+00:00",
        "finished_at": "2026-11-06T00:01:00+00:00",
        "reporting": {},
        "document_metrics": {},
        "phases": [
            {"name": "detection", "lines": [], "mappings": [],
             "summary": {"total_detected_violations": 5, "total_distinct_violations": 1,
                         "violation_names": ["invalid-annotation"], "violations_by_name": {"invalid-annotation": 5}}},
            {"name": "correction", "lines": [], "corrections": [
                {"violation_name": "figure-structure-alternate-description-missing", "affected_element": "", "page": 12, "lines": [figure_line]},
                *[{"violation_name": "figure-structure-alternate-description-missing", "affected_element": "", "page": p, "lines": [logo_line]} for p in (1, 2, 3)],
                {"violation_name": "missing-metadata-stream-dc-title", "affected_element": "", "page": None,
                 "lines": [{"level": "review", "message": "No document title was found; the file name was used as title: 'report final'. Please enter the real title."}]},
            ]},
            {"name": "verification", "lines": [], "mappings": [],
             "summary": {"total_detected_violations": 7, "total_distinct_violations": 1,
                         "violation_names": ["invalid-annotation"], "violations_by_name": {"invalid-annotation": 7},
                         "total_corrected_violations": -2, "corrected_by_name": {}}},
        ],
    }


def test_review_items_are_grouped_and_deduplicated():
    groups = build_review_groups(_report())
    images = next(g for g in groups if g.key == "images")
    assert [g.key for g in groups][:2] == ["title", "images"]          # "Please check" groups, fixed order
    assert len(images.items) == 2                                       # the logo on 3 pages is one item
    logo = next(i for i in images.items if i.value == "University logo")
    assert logo.occurrences == 3 and logo.pages == [1, 2, 3]
    assert estimated_minutes(groups) >= 1


def test_review_list_is_optional_and_pictures_can_be_switched_off():
    report = _report()
    without_list = build_customer_report_markdown(report)
    assert "## Things to Check" not in without_list
    assert "turn on “Show a list of things to check”" in without_list

    with_pictures = build_customer_report_markdown(report, include_review_list=True, include_pictures=True)
    assert "![Picture from page 12." in with_pictures
    assert "Compare with the caption: Figure 3" in with_pictures

    without_pictures = build_customer_report_markdown(report, include_review_list=True, include_pictures=False)
    assert "![" not in without_pictures
    assert "Compare with the caption: Figure 3" in without_pictures  # still checkable without seeing the page


def test_new_problems_are_shown_instead_of_negative_fixes():
    markdown = build_customer_report_markdown(_report())
    assert "| 5 | 0 | 7 (2 new) |" in markdown
    assert "-2" not in markdown


def test_pdf_report_contains_the_review_picture():
    report = _report()
    assert build_customer_report_images(report)
    with fitz.open(stream=build_customer_report_pdf(report, include_review_list=True, include_pictures=True)) as pdf:
        assert sum(len(page.get_images()) for page in pdf) == 1
    with fitz.open(stream=build_customer_report_pdf(report, include_review_list=True, include_pictures=False)) as pdf:
        assert sum(len(page.get_images()) for page in pdf) == 0
